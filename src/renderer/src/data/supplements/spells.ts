/** 'VSM' etc. + optional material text */
function comp(flags: string, m?: string): SpellDef['components'] {
  return { v: flags.includes('V'), s: flags.includes('S'), ...(m ? { m } : {}) }
}

type Extra = Partial<Pick<SpellDef, 'higherLevels' | 'attack' | 'save' | 'damage' | 'heal' | 'ritual'>> & {
  more?: string
  tags?: string[]
}

function sp(
  book: BookKey,
  name: string,
  level: number,
  school: SpellDef['school'],
  castingTime: string,
  range: string,
  components: SpellDef['components'],
  duration: string,
  classes: string[],
  summary: string,
  extra: Extra = {}
): SpellDef {
  const { more, tags, ritual, ...rest } = extra
  const id = 'sup-' + name.toLowerCase().replace(/[’']/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')
  return {
    id,
    name,
    kind: 'spell',
    source: 'Supplement',
    sourceBook: BOOKS[book],
    level,
    school,
    castingTime,
    range,
    components,
    duration,
    concentration: duration.startsWith('Concentration'),
    ritual: ritual ?? false,
    classes,
    summary,
    description: more ? `${summary} ${more}` : summary,
    tags: ['supplement', book, ...(tags ?? [])],
    ...rest
  }
}

